IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'CarFitness')
BEGIN
    CREATE TABLE dbo.CarFitness (
        FitnessId INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_CarFitness_FitnessId PRIMARY KEY CLUSTERED,
        CarId INT NOT NULL CONSTRAINT FK_CarFitness_Cars FOREIGN KEY REFERENCES dbo.Cars(CarId),
