-- ===================== CarInsurance =====================
-- NOTE: live schema uses CarInsuranceId (not InsuranceId) and Note (not Comments).
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='CarInsurance' AND COLUMN_NAME='CarInsuranceId')
BEGIN
    ALTER TABLE dbo.CarInsurance ADD CarInsuranceId INT IDENTITY(1,1) NOT NULL;
END
GO

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='CarInsurance' AND COLUMN_NAME='EndDate')
BEGIN
    ALTER TABLE dbo.CarInsurance ADD EndDate DATETIME NULL;
END
GO

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='CarInsurance' AND COLUMN_NAME='Note')
BEGIN
    ALTER TABLE dbo.CarInsurance ADD Note NVARCHAR(MAX) NULL;
END
GO

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='CarInsurance' AND COLUMN_NAME='IsActive')
BEGIN
    ALTER TABLE dbo.CarInsurance ADD IsActive BIT NOT NULL CONSTRAINT DF_CarInsurance_IsActive DEFAULT (1);
END
GO

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE TABLE_NAME='CarInsurance' AND CONSTRAINT_TYPE='PRIMARY KEY')
BEGIN
    ALTER TABLE dbo.CarInsurance ADD CONSTRAINT PK_CarInsurance_CarInsuranceId PRIMARY KEY CLUSTERED (CarInsuranceId);
END
GO

